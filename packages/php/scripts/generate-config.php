 * Every runwisp.toml key as a PHPStan type, which PHPStan and PhpStorm check
 * the options against: Config is a whole runwisp.toml, TaskConfig one
 * [tasks.<name>] table, ServiceConfig one [services.<name>] table. Use one
 * with `@phpstan-import-type TaskConfig from \RunWisp\Schema`.
 *
$doc */
final class Schema
{
}

PHP);
