// Generates src/Schema.php from runwisp.toml's JSON Schema: PHPStan types for
// every config key RunWisp accepts, so the options are checked and completed
// with no SDK change. The PHP twin of packages/js/scripts/generate-config.ts.
// Needs only PHP: no Composer dependencies.

declare(strict_types=1);

$root = dirname(__DIR__);
$schemaPath = "$root/../../apps/runwisp/internal/config/config.schema.json";
$outputFile = "$root/src/Schema.php";

$schema = json_decode((string) file_get_contents($schemaPath), true, 512, JSON_THROW_ON_ERROR);
if (!is_array($schema) || !is_array($schema['$defs'] ?? null)) {
    throw new RuntimeException("$schemaPath has no \$defs");
}
// This package is Apache-2.0 and the daemon GPL: generate only from a schema
// that is itself Apache-2.0.
if (!str_contains((string) ($schema['$comment'] ?? ''), 'SPDX-License-Identifier: Apache-2.0')) {
    throw new RuntimeException("$schemaPath must declare SPDX-License-Identifier: Apache-2.0 in \$comment");
}
$defs = $schema['$defs'];

/** A def with properties gets an alias; others are short enough to inline. */
function alias(string $def): string
{
    return ucfirst($def) . 'Config';
}

/** @param array<string, mixed> $node */
function type(array $node, array $defs, string $indent = ''): string
{
    if (isset($node['$ref'])) {
        $def = substr($node['$ref'], strlen('#/$defs/'));

        return isset($defs[$def]['properties']) ? alias($def) : type($defs[$def], $defs, $indent);
    }
    if (isset($node['enum'])) {
        return implode('|', array_map(static fn (mixed $v): string => var_export($v, true), $node['enum']));
    }
    foreach (['anyOf', 'oneOf'] as $union) {
        if (isset($node[$union])) {
            return implode('|', array_map(static fn (array $n): string => type($n, $defs, $indent), $node[$union]));
        }
    }
    if (is_array($node['type'] ?? null)) {
        return implode('|', array_map(static fn (string $t): string => type(['type' => $t], $defs), $node['type']));
    }

    return match ($node['type'] ?? null) {
        'string' => 'string',
        'integer' => 'int',
        'number' => 'int|float',
        'boolean' => 'bool',
        'array' => 'list<' . type($node['items'] ?? [], $defs, $indent) . '>',
        'object' => object($node, $defs, $indent),
        default => 'mixed',
    };
}

/**
 * A sealed array shape for an object with properties (and those of the defs
 * it extends with allOf), else a map.
 *
 * @param array<string, mixed> $node
 */
function object(array $node, array $defs, string $indent): string
{
    $properties = [];
    foreach ($node['allOf'] ?? [] as $base) {
        $properties = [...$properties, ...$defs[substr($base['$ref'], strlen('#/$defs/'))]['properties']];
    }
    $properties = [...$properties, ...$node['properties'] ?? []];
    $extra = $node['additionalProperties'] ?? null;
    if ($properties === [] || is_array($extra)) {
        // ponytail: a shape with extra keys of a type (composeAlias) is a plain map; PHPStan's unsealed shapes could say more.
        return 'array<string, ' . (is_array($extra) ? type($extra, $defs, $indent) : 'mixed') . '>';
    }
    $required = array_flip($node['required'] ?? []);
    $inner = "$indent    ";
    $lines = [];
    foreach ($properties as $key => $property) {
        $name = preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $key) === 1 ? $key : var_export($key, true);
        $lines[] = $inner . $name . (isset($required[$key]) ? '' : '?') . ': ' . type($property, $defs, $inner) . ',';
    }

    return "array{\n" . implode("\n", $lines) . "\n$indent}";
}

$aliases = ['Config' => type([...$schema, 'type' => 'object'], $defs)];
foreach ($defs as $def => $node) {
    if (isset($node['properties']) && $def !== 'unitCommon') {
        $aliases[alias($def)] = type($node, $defs);
    }
}
$doc = '';
foreach ($aliases as $name => $type) {
    $doc .= " * @phpstan-type $name " . str_replace("\n", "\n * ", $type) . "\n";
}

